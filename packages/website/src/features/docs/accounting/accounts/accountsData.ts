export interface AccountEntry {
    number: string
    slug: string
    label: string
    description?: string
    classNumber: number
    className: string
    type: "bilan" | "résultat"
    side: "actif" | "passif" | "actif ou passif" | "charge" | "produit"
    system: "minimal" | "facultatif"
    parent: string | null
}

function toSlug(number: string): string {
    return number
}

function defineAccount(
    number: string,
    label: string,
    options: {
        description?: string
        classNumber: number
        className: string
        type: "bilan" | "résultat"
        side: "actif" | "passif" | "actif ou passif" | "charge" | "produit"
        system: "minimal" | "facultatif"
        parent: string | null
    },
): AccountEntry {
    return {
        number,
        slug: toSlug(number),
        label,
        description: options.description,
        classNumber: options.classNumber,
        className: options.className,
        type: options.type,
        side: options.side,
        system: options.system,
        parent: options.parent,
    }
}

